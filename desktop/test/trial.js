const { evaluate, encode, DAY } = require('../src/trial');
let ok = 0, ko = 0;
const check = (n, c, x) => { if (c) { ok++; console.log('  ✓', n); } else { ko++; console.log('  ✗', n, x ?? ''); } };
const mem = (raw = null) => { const s = { raw, read: () => s.raw, write: (v) => { s.raw = v; } }; return s; };
const t0 = Date.UTC(2026, 9, 27);
console.log('Période d\'essai');
let a = mem(), b = mem();
let r = evaluate({ now: t0, stores: [a, b] });
check('premier lancement : ok, 30 jours, date écrite partout', r.state === 'ok' && r.daysLeft === 30 && a.raw && a.raw === b.raw, r);
r = evaluate({ now: t0 + 10 * DAY, stores: [a, b] });
check('10 jours plus tard : 20 jours restants', r.state === 'ok' && r.daysLeft === 20, r);
r = evaluate({ now: t0 + 29 * DAY + 1000, stores: [a, b] });
check('J+29 : 1 jour restant', r.state === 'ok' && r.daysLeft === 1, r);
r = evaluate({ now: t0 + 30 * DAY, stores: [a, b] });
check('J+30 : terminé', r.state === 'expired', r);
const c = mem();
r = evaluate({ now: t0 + 40 * DAY, stores: [c, a] });
check('un emplacement effacé ne remet pas le compteur à zéro', r.state === 'expired', r);
r = evaluate({ now: t0 + 40 * DAY, stores: [mem(), mem(encode(t0 + 39 * DAY, t0 + 39 * DAY)), a] });
check('la date la plus ancienne l\'emporte', r.state === 'expired', r);
r = evaluate({ now: t0 + 5 * DAY, stores: [mem('{"first":1,"last":2,"sig":"x"}')] });
check('fichier modifié à la main (seul) : refusé', r.state === 'tampered', r);
r = evaluate({ now: t0 + 5 * DAY, stores: [mem('{"first":1,"last":2,"sig":"x"}'), mem(encode(t0, t0))] });
check('un fichier altéré parmi des valides : ignoré', r.state === 'ok' && r.daysLeft === 25, r);
const d = mem();
evaluate({ now: t0 + 10 * DAY, stores: [d] });
r = evaluate({ now: t0 + 2 * DAY, stores: [d] });
check('horloge reculée de plus d\'un jour : refusé', r.state === 'tampered', r);
r = evaluate({ now: t0 + 10 * DAY - 3600000, stores: [d] });
check('petit décalage d\'horloge (moins d\'un jour) toléré', r.state === 'ok', r);
const bad = { read: () => { throw new Error('refusé'); }, write: () => { throw new Error('refusé'); } };
r = evaluate({ now: t0, stores: [bad, mem()] });
check('emplacement inaccessible : les autres suffisent', r.state === 'ok', r);
console.log(`\n${ok} vérifications réussies, ${ko} échec(s)`);
process.exit(ko ? 1 : 0);
