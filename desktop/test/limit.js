const fs = require('fs'), os = require('os'), path = require('path');
const { make, check, DAY } = require('../src/limit');
let ok = 0, ko = 0;
const t = (n, c) => { if (c) { ok++; console.log('  ✓', n); } else { ko++; console.log('  ✗', n); } };
const d = fs.mkdtempSync(path.join(os.tmpdir(), 'lim-')), file = path.join(d, 'usage-limit.json'), state = path.join(d, 'usage.json');
const T0 = Date.parse('2026-10-27T08:00:00Z');
t('sans fichier : aucune limite', check({ file, stateFile: state, now: T0 }).status === 'none');
fs.writeFileSync(file, JSON.stringify(make(30, T0)));
let r = check({ file, stateFile: state, now: T0 + DAY });
t('jour 1 : valide, 29 jours restants', r.status === 'ok' && r.daysLeft === 29);
r = check({ file, stateFile: state, now: T0 + 29 * DAY });
t('jour 29 : valide, 1 jour restant', r.status === 'ok' && r.daysLeft === 1);
t('jour 30 : expirée', check({ file, stateFile: state, now: T0 + 30 * DAY }).status === 'expired');
t('jour 45 : expirée', check({ file, stateFile: state, now: T0 + 45 * DAY }).status === 'expired');
fs.rmSync(state);
t('horloge reculée après un passage tardif : refusée', (() => { check({ file, stateFile: state, now: T0 + 20 * DAY }); return check({ file, stateFile: state, now: T0 + 2 * DAY }).status === 'clock'; })());
fs.rmSync(state);
t('horloge antérieure à la fabrication : refusée', check({ file, stateFile: state, now: T0 - 5 * DAY }).status === 'clock');
const l = make(30, T0); l.expires = new Date(T0 + 3650 * DAY).toISOString(); fs.writeFileSync(file, JSON.stringify(l));
t('date d\'expiration modifiée : fichier invalide', check({ file, stateFile: state, now: T0 }).status === 'tampered');
fs.writeFileSync(file, '{pas du json');
t('fichier corrompu : invalide', check({ file, stateFile: state, now: T0 }).status === 'tampered');
console.log(`\n${ok} vérifications réussies, ${ko} échec(s)`);
process.exit(ko ? 1 : 0);
